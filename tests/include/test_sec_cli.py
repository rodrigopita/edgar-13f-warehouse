import json

from include import sec_cli


def test_reconcile_sql_reads_only_the_profiles_and_prints_the_queries(tmp_path, capsys):
    rows = {"SUBMISSION": 1, "COVERPAGE": 1, "INFOTABLE": 2, "OTHERMANAGER": 0}
    rows |= {"OTHERMANAGER2": 0, "SIGNATURE": 1, "SUMMARYPAGE": 1}
    for name in ("2013q2_form13f", "2013q3_form13f"):
        (tmp_path / f"{name}.json").write_text(json.dumps({"name": f"{name}.zip", "rows": rows}))
    (tmp_path / "candidates.json").write_text("[]")

    sec_cli.main(["reconcile-sql", "--out", str(tmp_path)])

    printed = capsys.readouterr().out
    assert printed.startswith("-- Generated by `python -m include.sec_cli reconcile-sql` from 2")
    assert "('2013q3', 'INFOTABLE', 2)" in printed
